-- ensure id has default/identity
do $$
begin
  if (select pg_get_expr(adbin, adrelid)
      from pg_attrdef d
      join pg_attribute a on a.attrelid=d.adrelid and a.attnum=d.adnum
      join pg_class t on t.oid=d.adrelid
      where t.relname='offers' and a.attname='id') is null then
    execute 'create sequence if not exists public.offers_id_seq';
    execute 'alter table public.offers alter column id set default nextval(''public.offers_id_seq'')';
  end if;

  execute 'update public.offers set id = nextval(''public.offers_id_seq'') where id is null';

  begin
    execute 'alter table public.offers alter column id set not null';
  exception when others then null;
  end;
end $$;

