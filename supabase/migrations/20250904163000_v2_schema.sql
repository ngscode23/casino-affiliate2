-- ⚠️ LEGACY FK partner_offers.offer_slug -> offers.slug
-- Только если колонка offer_slug СУЩЕСТВУЕТ. Иначе — пропускаем.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='partner_offers' and column_name='offer_slug'
  ) then
    -- убрать старый FK, если висит с другим именем/формой
    if exists (
      select 1 from information_schema.table_constraints
      where constraint_schema='public'
        and table_name='partner_offers'
        and constraint_name='partner_offers_offer_slug_fkey'
        and constraint_type='FOREIGN KEY'
    ) then
      execute 'alter table public.partner_offers drop constraint partner_offers_offer_slug_fkey';
    end if;

    -- повесить нужный FK, если ещё нет
    if not exists (
      select 1
      from information_schema.table_constraints tc
      join information_schema.key_column_usage kcu
        on kcu.constraint_name = tc.constraint_name and kcu.constraint_schema = tc.constraint_schema
      where tc.table_schema='public'
        and tc.table_name='partner_offers'
        and tc.constraint_type='FOREIGN KEY'
        and kcu.column_name='offer_slug'
    ) then
      execute $x$
        alter table public.partner_offers
          add constraint partner_offers_offer_slug_fkey
          foreign key (offer_slug) references public.offers(slug)
          on delete cascade
      $x$;
    end if;
  else
    raise notice 'partner_offers.offer_slug absent; skipping legacy FK to offers.slug';
  end if;
end $$;

