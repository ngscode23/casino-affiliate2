begin
  select data_type into coltype
  from information_schema.columns
  where table_schema='public' and table_name='impressions' and column_name='id';

  if coltype = 'uuid' then
    select c.conname into pk_name
    from pg_constraint c
    join pg_class t on t.oid=c.conrelid
    where t.relname='impressions' and c.contype='p';
    if pk_name is not null then
      execute format('alter table public.impressions drop constraint %I', pk_name);
    end if;
    execute 'alter table public.impressions drop column id';
    execute 'alter table public.impressions add column id bigint generated by default as identity primary key';
  end if;
end $$;

